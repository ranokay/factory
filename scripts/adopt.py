class Problem(Exception):
    pass


def problem(message):
    raise Problem(message)


class Finding(NamedTuple):
    key: str
    display: str


def finding(category, path, rule, display):
    return Finding(f"{category}:{path}:{rule}", display)


def digest(key):
    return hashlib.sha256(key.encode()).hexdigest()[:12]


def run(arguments, cwd=None):
    try:
        return subprocess.run(  # nosec B603 B607 -- argument lists, never a shell
            arguments,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            timeout=TIMEOUT,
        )
    except subprocess.TimeoutExpired:
        problem(f"{arguments[0]} timed out after {TIMEOUT}s")
    except OSError as error:
        problem(f"cannot run {arguments[0]}: {error}")


def gh(*arguments):
    result = run(["gh", *arguments])
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        problem(f"gh {' '.join(arguments[:2])} failed: {detail}")
    return result.stdout


def git(project, *arguments):
    return run(["git", "-C", str(project), *arguments])


def git_out(project, *arguments):
    result = git(project, *arguments)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        problem(f"git {arguments[0]} failed: {detail}")
    return result.stdout


def parse_json(text, label):
    try:
        return json.loads(text)
    except json.JSONDecodeError as error:
        problem(f"{label} did not print JSON: {error}")


def valid_repo(value):
    return bool(REPO_RE.match(value)) and all(
        part not in (".", "..") for part in value.split("/")
    )


def read_file(project, path):
    target = project / path
    try:
        with target.open("rb") as handle:
            head = handle.read(1024)
            if b"\0" in head:
                return ""
            data = head + handle.read(MAX_TEXT + 1 - len(head))
    except OSError as error:
        problem(f"cannot read {path}: {error}")
    if len(data) > MAX_TEXT:
        problem(f"{path} is larger than {MAX_TEXT} bytes; adopt cannot inventory it")
    return data.decode("utf-8", "ignore")


def is_test_path(path):
    item = PurePosixPath(path)
    if any(part in TEST_DIRS for part in item.parts[:-1]):
        return True
    if item.name.startswith("test_"):
        return True
    return bool(TEST_NAME_RE.search(item.name))


def comment_rule(message):
    if message.startswith("commented-out code"):
        return "commented-out-code"
    match = re.search(r"\b(TODO|FIXME|HACK|XXX)\b", message)
    if match:
        return match.group(1)
    return "comment"


def valid_factory_include(value):
    if not isinstance(value, str) or "profiles/" not in value:
        return False
    return (
        "ranokay/factory" in value
        or value.startswith("./profiles/")
        or value.startswith("profiles/")
    )


def tooling_findings(project, tracked):
    present = set(tracked)
    found = []
    if "mise.toml" not in present:
        found.append(
            finding(
                "tooling",
                "mise.toml",
                "missing",
                "mise.toml is missing the Factory Profile include.",
            )
        )
    else:
        try:
            mise = tomllib.loads(read_file(project, "mise.toml"))
        except tomllib.TOMLDecodeError as error:
            found.append(
                finding(
                    "tooling",
                    "mise.toml",
                    "invalid-toml",
                    f"mise.toml is not valid TOML: {error}",
                )
            )
        else:
            includes = mise.get("include") or []
            tasks = (mise.get("task_config") or {}).get("includes") or []
            if not (
                any(valid_factory_include(value) for value in includes)
                and any(valid_factory_include(value) for value in tasks)
            ):
                found.append(
                    finding(
                        "tooling",
                        "mise.toml",
                        "factory-include",
                        "mise.toml is missing the Factory Profile include.",
                    )
                )
    if "hk.pkl" not in present:
        found.append(
            finding(
                "tooling",
                "hk.pkl",
                "missing",
                "hk.pkl is not amending a Factory Profile.",
            )
        )
    else:
        amended = re.search(r'(?m)^\s*amends\s+"([^"]+)"', read_file(project, "hk.pkl"))
        if not amended or not valid_factory_include(amended.group(1)):
            found.append(
                finding(
                    "tooling",
                    "hk.pkl",
                    "factory-amend",
                    "hk.pkl is not amending a Factory Profile.",
                )
            )
    if "renovate.json" not in present:
        found.append(
            finding(
                "tooling",
                "renovate.json",
                "missing",
                "renovate.json is not extending github>ranokay/factory.",
            )
        )
    else:
        try:
            renovate = json.loads(read_file(project, "renovate.json"))
        except json.JSONDecodeError as error:
            found.append(
                finding(
                    "tooling",
                    "renovate.json",
                    "invalid-json",
                    f"renovate.json is not valid JSON: {error}",
                )
            )
        else:
            extends = renovate.get("extends") or []
            values = [extends] if isinstance(extends, str) else extends
            if "github>ranokay/factory" not in values:
                found.append(
                    finding(
                        "tooling",
                        "renovate.json",
                        "factory-preset",
                        "renovate.json is not extending github>ranokay/factory.",
                    )
                )
    for path in (".coderabbit.yaml", ".greptile/config.json"):
        if path not in present:
            found.append(
                finding(
                    "tooling",
                    path,
                    "missing",
                    f"{path} is missing from the repository.",
                )
            )
    return found


def comment_findings(project, tracked):
    files = [path for path in tracked if not path.lower().endswith((".md", ".markdown"))]
    occurrences = {}
    for start in range(0, len(files), BATCH_SIZE):
        batch = [f"./{path}" for path in files[start : start + BATCH_SIZE]]
        result = run(["sh", str(COMMENT_BAN), *batch], cwd=project)
        if result.returncode not in (0, 1):
            detail = (result.stderr or result.stdout).strip()
            problem(f"comment-ban exited {result.returncode}: {detail}")
        for line in (result.stdout + "\n" + result.stderr).splitlines():
            match = COMMENT_RE.match(line.strip())
            if not match:
                continue
            path = match.group("path").removeprefix("./")
            rule = comment_rule(match.group("message"))
            key = f"comments:{path}:{rule}"
            occurrences.setdefault(key, []).append(
                (path, int(match.group("line")), match.group("message"))
            )
    found = []
    for key in sorted(occurrences):
        items = occurrences[key]
        path, rule = key.removeprefix("comments:").rsplit(":", 1)
        lines = sorted({line for _, line, _ in items})
        if len(items) == 1:
            display = f"{path}:{lines[0]}: {items[0][2]}"
        else:
            shown = ", ".join(str(line) for line in lines)
            display = f"{path}: {rule} at lines {shown}"
        found.append(Finding(key, display))
    return found


def dead_code_findings(project, tracked):
    tokens = {}
    counts = {}
    for path in tracked:
        if path.endswith(".d.ts"):
            continue
        text = read_file(project, path)
        if not text:
            continue
        names = set(TOKEN_RE.findall(text))
        tokens[path] = names
        for name in names:
            counts[name] = counts.get(name, 0) + 1
    found = []
    for path in tracked:
        item = PurePosixPath(path)
        if not item.parts or item.parts[0] not in SOURCE_ROOTS:
            continue
        if item.suffix not in SOURCE_SUFFIXES or is_test_path(path):
            continue
        if item.stem in ENTRY_STEMS or item.stem.endswith(".config"):
            continue
        own = 1 if item.stem in tokens.get(path, set()) else 0
        if counts.get(item.stem, 0) <= own:
            found.append(
                finding(
                    "dead-code",
                    path,
                    "unreferenced",
                    f"{path} is not referenced outside itself.",
                )
            )
    return found


def agents_findings(project, tracked):
    found = []
    if "AGENTS.md" not in tracked:
        found.append(
            finding(
                "agents",
                "AGENTS.md",
                "missing",
                "AGENTS.md is missing; start from the Factory's project/AGENTS.md.",
            )
        )
    else:
        text = read_file(project, "AGENTS.md")
        if not PROFILES_RE.search(text):
            found.append(
                finding(
                    "agents",
                    "AGENTS.md",
                    "profiles",
                    "AGENTS.md has no Profiles: line.",
                )
            )
        if "mise run check" not in text:
            found.append(
                finding(
                    "agents",
                    "AGENTS.md",
                    "check",
                    "AGENTS.md does not name mise run check.",
                )
            )
        lines = len(text.splitlines())
        if lines > AGENTS_LINE_LIMIT:
            found.append(
                finding(
                    "agents",
                    "AGENTS.md",
                    "length",
                    f"AGENTS.md is {lines} lines; rewrite it to the minimum.",
                )
            )
    claude = project / "CLAUDE.md"
    if not claude.is_symlink() or os.readlink(claude) != "AGENTS.md":
        found.append(
            finding(
                "agents",
                "CLAUDE.md",
                "symlink",
                "CLAUDE.md is not a relative symlink to AGENTS.md.",
            )
        )
    return found


def stale_findings(project, tracked):
    found = []
    for path in tracked:
        item = PurePosixPath(path)
        if (
            item.name in STALE_NAMES
            or item.name.endswith(STALE_SUFFIXES)
            or item.name.endswith("~")
            or any(part in STALE_DIRS for part in item.parts[:-1])
        ):
            found.append(
                finding(
                    "stale-files",
                    path,
                    "artifact",
                    f"{path} is a tracked artifact.",
                )
            )
    return found


def verification_findings(project, tracked):
    skills = set()
    for path in tracked:
        item = PurePosixPath(path)
        if (
            len(item.parts) == 4
            and item.parts[:2] == (".agents", "skills")
            and item.parts[2].startswith("verify-")
            and item.name == "SKILL.md"
        ):
            skills.add(item.parts[2])
    if not skills:
        return [
            finding(
                "verification",
                ".agents/skills",
                "no-skill",
                "No .agents/skills/verify-<app>/SKILL.md is committed.",
            )
        ]
    found = []
    mise = read_file(project, "mise.toml")
    for name in sorted(skills):
        app = name.removeprefix("verify-")
        link = f".claude/skills/{name}"
        if link not in tracked:
            found.append(
                finding(
                    "verification",
                    link,
                    "symlink",
                    f"{link} is not a committed symlink.",
                )
            )
        features = f".agents/skills/{name}/references/features"
        if not any(path.startswith(features + "/") for path in tracked):
            found.append(
                finding(
                    "verification",
                    features,
                    "map",
                    f"{features}/ is missing.",
                )
            )
        if f"verify:{app}" not in mise:
            found.append(
                finding(
                    "verification",
                    "mise.toml",
                    f"verify-{app}",
                    f"mise.toml has no verify:{app} task.",
                )
            )
    return found



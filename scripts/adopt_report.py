#!/usr/bin/env python3
"""Marker rendering and lookup for the adopt inventory."""

import re

from adopt_common import digest, gh, parse_json, problem

DISCLAIMER = "> *This was generated by AI during adopt.*"
MARKER = "factory:adopt"
MARKER_RE = re.compile(
    r"<!--\s*factory:adopt\s+category=([a-z-]+)\s+finding=([0-9a-f]{12})\s*-->"
)
SEARCH_PAGE_SIZE = 100
SEARCH_MAX_PAGES = 10


def code_span(value):
    text = " ".join(str(value).split())
    if len(text) > 240:
        text = text[:237] + "..."
    runs = re.findall(r"`+", text)
    if not runs:
        return f"`{text}`"
    fence = "`" * (max(len(run) for run in runs) + 1)
    return f"{fence} {text} {fence}"


def body_for(category, findings, total, repo, head):
    lines = [DISCLAIMER, ""]
    for item in findings:
        lines.append(
            f"<!-- {MARKER} category={category['key']} finding={digest(item.key)} -->"
        )
    count = len(findings)
    noun = "finding" if count == 1 else "findings"
    if count == total:
        found = f"`adopt` found {count} unseen {noun} in this category."
    else:
        found = f"`adopt` found {count} of {total} unseen {noun} in this category."
    lines.extend(["", f"## {category['title']}", "", found, ""])
    for item in findings:
        lines.append(f"- {code_span(item.display)}")
    lines.extend(
        [
            "",
            "## Work it",
            "",
            category["instruction"],
            "",
            f"Filed from `{repo}` at `{head}`.",
        ]
    )
    return "\n".join(lines) + "\n"


def markers_in_body(body):
    found = []
    for line in str(body).splitlines():
        match = MARKER_RE.fullmatch(line.strip())
        if match:
            found.append((match.group(1), match.group(2)))
        elif found:
            break
    return found


def search_state(repo, state):
    label = f"{state} adopt issue search"
    query = f'repo:{repo} is:issue state:{state} "{MARKER}" in:body'
    seen = set()
    for page in range(1, SEARCH_MAX_PAGES + 1):
        result = gh(
            "api",
            "-X",
            "GET",
            "search/issues",
            "-f",
            f"q={query}",
            "-f",
            f"per_page={SEARCH_PAGE_SIZE}",
            "-f",
            f"page={page}",
        )
        data = parse_json(result, label)
        items = data.get("items")
        if not isinstance(items, list):
            problem(f"{label} did not return items")
        if data.get("incomplete_results") is True:
            problem(f"{label} returned incomplete results")
        for item in items:
            seen.update(markers_in_body(item.get("body") or ""))
        if len(items) < SEARCH_PAGE_SIZE:
            break
    else:
        problem(f"{label} filled all {SEARCH_MAX_PAGES} pages")
    return seen


def existing_markers(repo):
    seen = set()
    for state in ("open", "closed"):
        seen.update(search_state(repo, state))
    return seen

import json
import unittest

from pushback_test_support import TRIAGE_MARKER, PushbackCase


class Pushback(PushbackCase):
    def test_context_assembles_product_checks_and_the_full_pass(self):
        payload = self.context(1)
        self.assertEqual(payload["repo"], "o/one")
        self.assertEqual(payload["issue"]["number"], 1)
        self.assertIn("Reading Tracker", payload["product"])
        self.assertEqual(
            payload["non_goals"],
            ["No web dashboard or browser UI.", "No cloud sync or accounts."],
        )
        self.assertEqual(payload["pass"], "full")
        self.assertEqual(
            payload["checks"],
            [
                "evidence",
                "simplest",
                "overlap",
                "maintenance",
                "reversibility",
                "non-goals",
            ],
        )
        self.assertEqual(payload["prior"], [])
        self.assertEqual(payload["overrides"], [])

    def test_light_pass_for_promotion_and_reproduced_bugs(self):
        state = self.state()
        state["issues"]["1"]["labels"] = [{"name": "promotion"}, {"name": "bug"}]
        state["issues"]["3"]["labels"] = [{"name": "bug"}, {"name": "needs-triage"}]
        self.write_state(state)
        payload = self.context(1)
        self.assertEqual(payload["pass"], "light")
        self.assertEqual(payload["checks"], ["overlap", "simplest"])
        self.add_comment(3, f"{TRIAGE_MARKER}\n\n**Outcome:** reproduced")
        payload = self.context(3)
        self.assertEqual(payload["pass"], "light")
        self.assertTrue(payload["reproduced"])
        self.assertEqual(payload["checks"], ["overlap", "simplest"])
        payload = self.context(2)
        self.assertEqual(payload["pass"], "full")
        self.assertFalse(payload["reproduced"])

    def test_non_goal_conflict_records_dont_quoting_it_and_waits_for_confirmation(self):
        result = self.record(
            1,
            {
                "verdict": "don't",
                "reason": "A web dashboard conflicts with the product's stated scope.",
                "non_goal": "No web dashboard or browser UI.",
            },
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(len(self.comments(1)), 1)
        body = self.comments(1)[0]["body"]
        self.assertTrue(body.startswith("> *This was generated by AI during triage.*"), body)
        self.assertIn("<!-- factory:pushback verdict=don't pass=full -->", body)
        self.assertIn("**Verdict:** don't", body)
        self.assertIn('**Non-goal:** "No web dashboard or browser UI."', body)
        self.assertEqual(sorted(self.labels(1)), ["enhancement", "needs-triage"])
        self.assertNotEqual(self.gate(1).returncode, 0)
        confirmed = self.cli(
            "confirm-dont", "o/one", "1", "--reason", "ranokay confirmed the don't."
        )
        self.assertEqual(confirmed.returncode, 0, confirmed.stderr)
        self.assertEqual(sorted(self.labels(1)), ["enhancement", "wontfix"])
        self.assertIn("<!-- factory:pushback-confirm verdict=wontfix -->", self.comments(1)[-1]["body"])

    def test_dont_without_a_non_goal_is_valid(self):
        result = self.record(
            1,
            {
                "verdict": "don't",
                "reason": "The report already answers this and the maintenance cost is not worth it.",
            },
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        body = self.comments(1)[0]["body"]
        self.assertIn("**Verdict:** don't", body)
        self.assertNotIn("**Non-goal:**", body)
        self.assertEqual(sorted(self.labels(1)), ["enhancement", "needs-triage"])

    def test_reshape_acceptance_without_a_reason_changes_nothing(self):
        result = self.record(
            2,
            {
                "verdict": "reshape",
                "reason": "The report command already prints JSON.",
                "smaller": "Use the existing `reading report --json`.",
            },
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        before = self.issue(2)["body"]
        self.log.write_text("")
        refused = self.cli("accept-reshape", "o/one", "2")
        self.assertNotEqual(refused.returncode, 0)
        self.assertIn("--reason", refused.stderr)
        self.assertNotIn(["issue", "edit"], [call[:2] for call in self.calls()])
        self.assertEqual(self.issue(2)["body"], before)
        self.assertEqual(len(self.comments(2)), 1)
        self.assertNotIn("ready-for-agent", self.labels(2))

    def test_reshape_requires_acceptance_and_updates_the_body(self):
        smaller = "Use `reading report --json`; add the flag to `stats` only if a pipe needs it."
        result = self.record(
            2,
            {
                "verdict": "reshape",
                "reason": "The report command already prints JSON.",
                "smaller": smaller,
            },
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(self.labels(2)), ["enhancement", "needs-triage"])
        refused = self.gate(2)
        self.assertNotEqual(refused.returncode, 0)
        self.assertIn("accept-reshape", refused.stderr)
        accepted = self.cli(
            "accept-reshape",
            "o/one",
            "2",
            "--reason",
            "Accepted; the smaller version is the spec.",
        )
        self.assertEqual(accepted.returncode, 0, accepted.stderr)
        self.assertEqual(sorted(self.labels(2)), ["enhancement", "ready-for-agent"])
        self.assertEqual(self.gate(2).returncode, 0)
        self.assertIn("<!-- factory:reshape -->", self.issue(2)["body"])
        self.assertIn("## Reshaped scope", self.issue(2)["body"])
        self.assertIn(smaller, self.issue(2)["body"])
        self.assertIn("<!-- factory:pushback-accept verdict=reshape accepted=true -->", self.comments(2)[-1]["body"])
        again = self.cli("accept-reshape", "o/one", "2")
        self.assertEqual(again.returncode, 0, again.stderr)
        self.assertEqual(len(self.comments(2)), 2)
        self.assertEqual(self.issue(2)["body"].count("factory:reshape"), 1)

    def test_go_applies_ready_for_agent_and_a_second_review_is_refused(self):
        result = self.record(
            3, {"verdict": "go", "reason": "Small, in scope and the log already holds the data."}
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(self.labels(3)), ["enhancement", "ready-for-agent"])
        self.assertEqual(self.gate(3).returncode, 0)
        self.assertEqual(len(self.comments(3)), 1)
        self.assertEqual(
            self.context(3)["prior"][0]["reason"],
            "Small, in scope and the log already holds the data.",
        )
        again = self.record(
            3, {"verdict": "go", "reason": "A second review must not post."}
        )
        self.assertNotEqual(again.returncode, 0)
        self.assertIn("already has a pushback verdict", again.stderr)
        self.assertEqual(len(self.comments(3)), 1)

    def test_override_is_recorded_and_appears_in_the_next_context(self):
        self.assertEqual(
            self.record(
                1,
                {
                    "verdict": "don't",
                    "reason": "A dashboard conflicts with the stated non-goal.",
                    "non_goal": "No web dashboard or browser UI.",
                },
            ).returncode,
            0,
        )
        result = self.cli(
            "override", "o/one", "1", "--reason", "ranokay wants the dashboard anyway."
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(self.labels(1)), ["enhancement", "ready-for-agent"])
        self.assertEqual(self.gate(1).returncode, 0)
        override_body = self.comments(1)[-1]["body"]
        self.assertIn("<!-- factory:pushback-override verdict=go accepted=don't -->", override_body)
        self.assertIn("**Reason:** ranokay wants the dashboard anyway.", override_body)
        state = self.state()
        state["search"] = [1]
        self.write_state(state)
        payload = self.context(2)
        self.assertEqual(
            payload["overrides"],
            [
                {
                    "issue": 1,
                    "reason": "ranokay wants the dashboard anyway.",
                    "url": "https://example.test/issue/1#issuecomment-2",
                    "verdict": "don't",
                }
            ],
        )
        again = self.cli("override", "o/one", "1", "--reason", "A second override.")
        self.assertNotEqual(again.returncode, 0)
        self.assertIn("already has an override", again.stderr)

    def test_needs_info_requires_the_exact_question(self):
        result = self.record(2, {"verdict": "needs-info", "reason": "The format is unclear."})
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("question", result.stderr)
        self.assertEqual(self.comments(2), [])
        result = self.record(
            2,
            {
                "verdict": "needs-info",
                "reason": "The format is unclear.",
                "question": "Which fields must the JSON output contain?",
            },
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(self.labels(2)), ["enhancement", "needs-info"])
        self.assertIn("**Question:** Which fields must the JSON output contain?", self.comments(2)[0]["body"])
        self.assertNotEqual(self.gate(2).returncode, 0)

    def test_promotion_only_issue_records_a_light_verdict_without_a_category(self):
        state = self.state()
        state["issues"]["1"]["labels"] = [{"name": "promotion"}]
        self.write_state(state)
        self.assertEqual(self.context(1)["pass"], "light")
        result = self.record(
            1, {"verdict": "go", "reason": "The correction is enforceable and adds no surface."}
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(self.labels(1)), ["promotion", "ready-for-agent"])
        self.assertEqual(self.gate(1).returncode, 0)

    def test_needs_info_answer_permits_one_fresh_review(self):
        first = self.record(
            2,
            {
                "verdict": "needs-info",
                "reason": "The format is unclear.",
                "question": "Which fields must the JSON output contain?",
            },
        )
        self.assertEqual(first.returncode, 0, first.stderr)
        unanswered = self.record(
            2,
            {"verdict": "go", "reason": "The answer settles the format."},
            "--again",
        )
        self.assertNotEqual(unanswered.returncode, 0)
        self.assertIn("answer comment", unanswered.stderr)
        state = self.state()
        state["issues"]["2"]["author"] = {"login": "reporter"}
        self.write_state(state)
        self.add_comment(2, "The fields are pages and week.", author="outsider")
        outside = self.record(
            2,
            {"verdict": "go", "reason": "The answer settles the format."},
            "--again",
        )
        self.assertNotEqual(outside.returncode, 0)
        self.assertIn("reporter or ranokay", outside.stderr)
        self.add_comment(2, "The fields are pages and week.", author="reporter")
        refused = self.record(
            2, {"verdict": "go", "reason": "The answer settles the format."}
        )
        self.assertNotEqual(refused.returncode, 0)
        self.assertIn("--again", refused.stderr)
        result = self.record(
            2,
            {"verdict": "go", "reason": "The answer settles the format."},
            "--again",
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(sorted(self.labels(2)), ["enhancement", "ready-for-agent"])
        self.assertEqual(self.gate(2).returncode, 0)
        self.assertEqual(len(self.comments(2)), 4)
        self.assertEqual(
            [comment["body"].count("factory:pushback verdict=") for comment in self.comments(2)],
            [1, 0, 0, 1],
        )

    def test_malformed_verdict_is_refused_before_gh(self):
        cases = (
            "not json",
            {"reason": "no verdict"},
            {"verdict": "maybe", "reason": "unknown verdict"},
            {"verdict": "go"},
            {"verdict": "go", "reason": "extra field", "extra": 1},
            {"verdict": "reshape", "reason": "no smaller version"},
            {"verdict": "needs-info", "reason": "no question"},
            {"verdict": "go", "reason": "a smaller version on go", "smaller": "not allowed"},
            {"verdict": "go", "reason": "a question on go", "question": "not allowed"},
            {"verdict": "go", "reason": "a non-goal on go", "non_goal": "No cloud sync or accounts."},
        )
        for data in cases:
            with self.subTest(data=data):
                self.reset()
                result = self.record(1, data)
                self.assertNotEqual(result.returncode, 0)
                self.assertEqual(self.calls(), [])


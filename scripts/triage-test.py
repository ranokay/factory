    def test_cleanup_name_is_markdown_safe(self):
        name = "stop` [x](https://example.com)"
        script = self.project / ".agents/skills/verify-counter/scripts/verify.py"
        text = script.read_text()
        for old, new in (
            ('{"name": "stop", "destructive": True', f'{{"name": {json.dumps(name)}, "destructive": True'),
            ('"stop": lambda: stop(dry),', f"{json.dumps(name)}: lambda: stop(dry),"),
        ):
            self.assertIn(old, text)
            text = text.replace(old, new, 1)
        script.write_text(text)
        result = self.triage(
            "reproduce",
            "--project",
            str(self.project),
            "o/one",
            "6",
            "--app",
            "counter",
            "--step",
            "launch",
            "--step",
            "count",
            "--observe",
            "count:count=0",
            "--cleanup",
            name,
        )
        self.assertEqual(result.returncode, 0, result.stderr)
        body = self.comment.read_text()
        self.assertIn(f"Cleanup `` {name} `` exited 0.", body)
        self.assertNotEqual(self.doctor().returncode, 0)


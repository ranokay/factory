#!/usr/bin/env python3
"""Triage an issue into the canonical labels and reproduce a bug through a verify skill.

The reproduction runs only commands the project's verify CLI lists, passed as
argv and never through a shell. Issue text is stored as data and is never
rendered into a comment. The evidence comment is posted before any label, and
the local evidence directory is deleted once both succeed.
"""

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess  # nosec B404 -- mise and gh run with an argument list, never a shell
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

CATEGORIES = ("bug", "enhancement")
STATES = ("needs-triage", "needs-info", "ready-for-agent", "ready-for-human", "wontfix")
DISCLAIMER = "> *This was generated by AI during triage.*"
MARKER = "<!-- factory:triage -->"
REPO = re.compile(r"^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$")
APP = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]*$")
TIMEOUT = 180
SKILL_ROOT = Path(".agents/skills")


class Problem(Exception):
    pass


def problem(message):
    raise Problem(message)


def valid_repo(value):
    return bool(REPO.match(value)) and all(part not in (".", "..") for part in value.split("/"))


def run_gh(*arguments):
    return subprocess.run(  # nosec B603 B607 -- gh from PATH with an argument list
        ["gh", *arguments], capture_output=True, text=True
    )


def gh(*arguments):
    result = run_gh(*arguments)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        problem(f"gh {' '.join(arguments[:2])} failed: {detail}")
    return result.stdout


def parse_json(text, label):
    try:
        return json.loads(text)
    except json.JSONDecodeError as error:
        problem(f"{label} did not print JSON: {error}")


def issue_labels(repo, issue):
    payload = parse_json(
        gh("issue", "view", str(issue), "-R", repo, "--json", "labels"), f"labels for {repo}#{issue}"
    )
    return [item["name"] for item in payload.get("labels") or []]


def apply_labels(repo, issue, category, state):
    if category not in CATEGORIES:
        problem(f"category must be one of {', '.join(CATEGORIES)}")
    if state not in STATES:
        problem(f"state must be one of {', '.join(STATES)}")
    current = issue_labels(repo, issue)
    triage = {name for name in current if name in CATEGORIES or name in STATES}
    remove = sorted(triage - {category, state})
    add = sorted({category, state} - set(current))
    if add or remove:
        command = ["issue", "edit", str(issue), "-R", repo]
        for name in add:
            command.extend(["--add-label", name])
        for name in remove:
            command.extend(["--remove-label", name])
        result = run_gh(*command)
        if result.returncode != 0:
            detail = (result.stderr or result.stdout).strip()
            problem(f"applying {category} and {state} failed: {detail}")
    after = issue_labels(repo, issue)
    categories = [name for name in after if name in CATEGORIES]
    states = [name for name in after if name in STATES]
    if categories != [category] or states != [state]:
        problem(
            f"labels are {categories or 'none'} and {states or 'none'}; "
            f"expected exactly {category} and {state}"
        )


def fetch_issue(repo, issue):
    return parse_json(
        gh("issue", "view", str(issue), "-R", repo, "--json", "number,title,body,updatedAt,labels"),
        f"issue {repo}#{issue}",
    )


def run_mise(project, task, arguments):
    command = ["mise", "run", task, "--", *arguments]
    try:
        return subprocess.run(  # nosec B603 B607 -- the project's own mise task and argv
            command, cwd=str(project), capture_output=True, text=True, timeout=TIMEOUT
        )
    except subprocess.TimeoutExpired:
        return SimpleNamespace(returncode=124, stdout="", stderr=f"timed out after {TIMEOUT}s")


def inventory(project, task):
    result = run_mise(project, task, ["commands"])
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        problem(f"mise run {task} -- commands exited {result.returncode}: {detail}")
    try:
        payload = json.loads(result.stdout)
    except json.JSONDecodeError:
        problem(f"mise run {task} -- commands did not print JSON")
    if payload.get("ok") is not True:
        problem(f"mise run {task} -- commands did not report ok: true")
    commands = payload.get("commands")
    if not isinstance(commands, list):
        problem(f"mise run {task} -- commands did not print a commands list")
    names = {}
    for item in commands:
        if not isinstance(item, dict) or not isinstance(item.get("name"), str):
            problem(f"mise run {task} -- commands has an entry without a name")
        names[item["name"]] = bool(item.get("destructive"))
    if not names:
        problem(f"mise run {task} -- commands is empty")
    return names


def parse_steps(values, names):
    steps = []
    for value in values:
        try:
            argv = shlex.split(value)
        except ValueError as error:
            problem(f"--step {value!r} is not a valid command line: {error}")
        if not argv:
            problem("--step must name a command")
        if argv[0] not in names:
            problem(
                f"--step {value!r} names {argv[0]!r}, which the verify CLI does not list; "
                f"commands: {', '.join(sorted(names))}"
            )
        steps.append(argv)
    return steps


def parse_observes(values, step_names):
    observes = []
    for value in values:
        step, separator, check = value.partition(":")
        if not separator or "=" not in check:
            problem(f"--observe {value!r} must be <step>:<key>=<value> or <step>:exit=<n>")
        key, _, expected = check.partition("=")
        if step not in step_names:
            problem(f"--observe {value!r} names a step that is not in --step")
        if not key:
            problem(f"--observe {value!r} has no key")
        if key == "exit":
            if not expected.isdigit():
                problem(f"--observe {value!r} needs a number for exit")
            expected = str(int(expected))
        observes.append({"step": step, "key": key, "expected": expected})
    return observes


def render(value):
    if value is True:
        return "true"
    if value is False:
        return "false"
    if value is None:
        return "null"
    if isinstance(value, str):
        return value
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(value, sort_keys=True)


def evaluate(observes, executions):
    rows = []
    for observe in observes:
        matching = [item for item in executions if item["step"] == observe["step"]]
        execution = matching[-1] if matching else None
        if observe["key"] == "exit":
            observed = str(execution["exit"]) if execution else "not run"
        elif execution is None:
            observed = "not run"
        elif not isinstance(execution["json"], dict):
            observed = "no JSON output"
        elif observe["key"] not in execution["json"]:
            observed = f"missing {observe['key']}"
        else:
            observed = render(execution["json"][observe["key"]])
        rows.append({**observe, "observed": observed, "match": observed == observe["expected"]})
    return rows


def cell(value):
    text = " ".join(str(value).split())
    if len(text) > 200:
        text = text[:197] + "..."
    return text.replace("|", "\\|")


def comment_body(issue, rows, executions, cleanup, cleanup_name):
    lines = [
        DISCLAIMER,
        "",
        MARKER,
        "",
        "## Reproduction",
        "",
        f"Issue #{issue.get('number')}, updated at {issue.get('updatedAt') or 'unknown'}.",
        "",
        f"**Outcome:** {'reproduced' if all(row['match'] for row in rows) else 'not reproduced'}",
        "",
        "**Steps**",
        "",
    ]
    for item in executions:
        lines.append(f"- `{cell(' '.join(item['argv']))}` — exit {item['exit']}")
    lines.extend(
        [
            "",
            "**Checks**",
            "",
            "| Step | Checked | Expected | Observed | Result |",
            "| --- | --- | --- | --- | --- |",
        ]
    )
    for row in rows:
        result = "match" if row["match"] else "mismatch"
        lines.append(
            f"| `{row['step']}` | `{row['key']}` | `{cell(row['expected'])}` "
            f"| `{cell(row['observed'])}` | {result} |"
        )
    lines.append("")
    if cleanup is not None:
        lines.append(f"Cleanup `{cleanup_name}` exited {cleanup['exit']}.")
        lines.append("")
    return "\n".join(lines)


def post_comment(repo, issue, body):
    handle = tempfile.NamedTemporaryFile("w", suffix=".md", delete=False)
    try:
        with handle:
            handle.write(body)
        result = run_gh("issue", "comment", str(issue), "-R", repo, "--body-file", handle.name)
    finally:
        os.unlink(handle.name)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        problem(f"posting the reproduction comment failed: {detail}")
    return result.stdout.strip()


def evidence_directory(repo, issue):
    root = (Path.home() / ".cache" / "factory").resolve()
    directory = (root / repo / f"issue-{issue}").resolve()
    if not directory.is_relative_to(root):
        problem(f"evidence path {directory} escapes {root}")
    return directory


def capture(project, task, steps, cleanup):
    executions = []
    cleanup_result = None
    try:
        for argv in steps:
            result = run_mise(project, task, argv)
            try:
                payload = json.loads(result.stdout)
            except json.JSONDecodeError:
                payload = None
            executions.append(
                {
                    "step": argv[0],
                    "argv": argv,
                    "exit": result.returncode,
                    "stdout": result.stdout,
                    "stderr": result.stderr,
                    "json": payload,
                }
            )
    finally:
        result = run_mise(project, task, [cleanup])
        cleanup_result = {"exit": result.returncode, "stdout": result.stdout, "stderr": result.stderr}
    return executions, cleanup_result


def reproduce(args):
    if not APP.match(args.app):
        problem(f"--app must name a verify skill, not {args.app!r}")
    project = Path(args.project).expanduser().resolve()
    skill = project / SKILL_ROOT / f"verify-{args.app}" / "SKILL.md"
    if not skill.is_file():
        problem(f"{skill} is missing; the project needs a verify-{args.app} skill")
    task = f"verify:{args.app}"
    names = inventory(project, task)
    if args.cleanup not in names:
        problem(
            f"--cleanup {args.cleanup!r} is not a command the verify CLI lists; "
            f"commands: {', '.join(sorted(names))}"
        )
    steps = parse_steps(args.step, names)
    if not any(names[argv[0]] and argv[0] != args.cleanup for argv in steps):
        problem(
            "the plan needs at least one destructive command other than --cleanup, "
            "so the app is actually driven"
        )
    observes = parse_observes(args.observe, {item[0] for item in steps})
    issue = fetch_issue(args.repo, args.issue)
    directory = evidence_directory(args.repo, args.issue)
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    (directory / "issue.json").write_text(json.dumps(issue, indent=2) + "\n")
    try:
        executions, cleanup = capture(project, task, steps, args.cleanup)
        (directory / "steps.json").write_text(json.dumps(executions, indent=2) + "\n")
        rows = evaluate(observes, executions)
        outcome = "reproduced" if all(row["match"] for row in rows) else "not-reproduced"
        url = post_comment(
            args.repo,
            args.issue,
            comment_body(issue, rows, executions, cleanup, args.cleanup),
        )
        state = "ready-for-agent" if outcome == "reproduced" else "needs-info"
        apply_labels(args.repo, args.issue, "bug", state)
    except Exception:
        print(f"triage: evidence kept at {directory}", file=sys.stderr)
        raise
    try:
        shutil.rmtree(directory)
    except OSError as error:
        print(f"triage: evidence kept at {directory}; deleting it failed: {error}", file=sys.stderr)
    print(json.dumps({"ok": True, "outcome": outcome, "comment": url, "labels": ["bug", state]}))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    labels = commands.add_parser("labels", help="apply exactly one category and one state label")
    labels.add_argument("repo")
    labels.add_argument("issue", type=int)
    labels.add_argument("--category", required=True, choices=CATEGORIES)
    labels.add_argument("--state", required=True, choices=STATES)
    reproduction = commands.add_parser("reproduce", help="reproduce a bug through the verify CLI")
    reproduction.add_argument("repo")
    reproduction.add_argument("issue", type=int)
    reproduction.add_argument("--project", default=".", help="project checkout (default: the current directory)")
    reproduction.add_argument("--app", required=True, help="the verify-<app> skill to drive")
    reproduction.add_argument("--step", action="append", required=True, help="a CLI command and its arguments")
    reproduction.add_argument(
        "--observe",
        action="append",
        required=True,
        help="<step>:<key>=<value> or <step>:exit=<n>; a repeated step observes its last execution",
    )
    reproduction.add_argument(
        "--cleanup",
        default="stop",
        help="the CLI command that tears the app down (default: stop)",
    )
    args = parser.parse_args(argv)
    try:
        if not valid_repo(args.repo):
            problem(f"repository must be <owner>/<repo>, not {args.repo!r}")
        if args.issue < 1:
            problem("issue must be a positive number")
        if args.command == "labels":
            apply_labels(args.repo, args.issue, args.category, args.state)
            print(json.dumps({"ok": True, "category": args.category, "state": args.state}))
            return 0
        reproduce(args)
        return 0
    except Problem as error:
        print(f"triage: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
